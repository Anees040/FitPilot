class _SearchField extends StatelessWidget {
  final ValueChanged<String> onChanged;
  final int count;

  const _SearchField({required this.onChanged, required this.count});

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final ext = theme.extension<AppColors>()!;

    return Container(
      decoration: BoxDecoration(
        color: ext.surfaceRaised,
        borderRadius: BorderRadius.circular(14),
        border: Border.all(color: ext.hairline),
      ),
      padding: const EdgeInsets.symmetric(horizontal: 14),
      child: Row(
        children: [
          Icon(Icons.search_rounded, size: 19, color: ext.textDisabled),
          const SizedBox(width: 10),
          Expanded(
            child: TextField(
              onChanged: onChanged,
              style: theme.textTheme.body,
              cursorColor: theme.colorScheme.primary,
              decoration: InputDecoration(
                border: InputBorder.none,
                hintText: 'Search $count photos or photographers',
                hintStyle: theme.textTheme.caption.copyWith(
                  color: ext.textDisabled,
                ),
              ),
            ),
          ),
        ],
      ),
    );
  }
}

class _CreditTile extends StatelessWidget {
  final ImageCredit credit;

  const _CreditTile({required this.credit});

  Future<void> _openSource(BuildContext context) async {
    if (credit.source.isEmpty) return;
    final uri = Uri.tryParse(credit.source);
    if (uri == null) return;
    // Best-effort: a device with no browser must not crash the screen.
    try {
      await launchUrl(uri, mode: LaunchMode.externalApplication);
    } catch (_) {}
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final ext = theme.extension<AppColors>()!;

    return AppCard(
      padding: const EdgeInsets.all(12),
      onTap: credit.source.isEmpty ? null : () => _openSource(context),
      child: Row(
        children: [
          FoodImage(
            name: credit.imageKey,
            imageKey: credit.imageKey,
            size: 52,
            radius: 12,
          ),
          const SizedBox(width: 13),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  _titleFor(credit.imageKey),
                  style: theme.textTheme.bodyStrong,
                  maxLines: 1,
                  overflow: TextOverflow.ellipsis,
                ),
                const SizedBox(height: 3),
                // Labelled explicitly. A bare username reads as noise; "Photo
                // by Nerd271" reads as a credit.
                Text(
                  credit.isPublicDomain
                      ? 'Public domain — no attribution required'
                      : 'Photo by ${credit.author}',
                  style: theme.textTheme.caption,
                  maxLines: 1,
                  overflow: TextOverflow.ellipsis,
                ),
                const SizedBox(height: 6),
                _LicenceChip(license: credit.license),
              ],
            ),
          ),
          if (credit.source.isNotEmpty)
            Icon(Icons.open_in_new_rounded, size: 16, color: ext.textDisabled),
        ],
      ),
    );
  }

  /// `gulab_jamun` → `Gulab jamun`
  static String _titleFor(String imageKey) {
    final words = imageKey.replaceAll('_', ' ');
    if (words.isEmpty) return words;
    return words[0].toUpperCase() + words.substring(1);
  }
}

/// The licence, prefixed so the code is recognisable as a licence rather than
/// looking like a stray product number.
class _LicenceChip extends StatelessWidget {
  final String license;

  const _LicenceChip({required this.license});

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final ext = theme.extension<AppColors>()!;

    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
      decoration: BoxDecoration(
        color: ext.surfaceRaised,
        borderRadius: BorderRadius.circular(6),
        border: Border.all(color: ext.hairline),
      ),
      child: Row(
        mainAxisSize: MainAxisSize.min,
        children: [
          Icon(Icons.balance_rounded, size: 11, color: ext.textDisabled),
          const SizedBox(width: 5),
          Text(
            'Licence: $license',
            style: theme.textTheme.overline.copyWith(color: ext.textDisabled),
          ),
        ],
      ),
    );
  }
}
