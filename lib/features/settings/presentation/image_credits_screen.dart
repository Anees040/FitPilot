/// Attribution for the bundled food photos.
///
/// This screen exists for a legal reason, not a decorative one: the photos come
/// from Wikimedia Commons under Creative Commons licences that require naming
/// the photographer and the licence. Those two facts used to be rendered bare —
/// a username like "Nerd271" and a code like "CC BY-SA 3.0" with nothing to say
/// what either was — which read as random noise. Everything here is now
/// labelled, explained, and links back to the original.
///
/// The list is generated by `tool/fetch_food_images.mjs` from the live Wikimedia
/// API. It is never hand-written, so it always matches what actually shipped.
class ImageCreditsScreen extends ConsumerStatefulWidget {
  const ImageCreditsScreen({super.key});

  @override
  ConsumerState<ImageCreditsScreen> createState() => _ImageCreditsScreenState();
}

class _ImageCreditsScreenState extends ConsumerState<ImageCreditsScreen> {
  String _query = '';

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final creditsAsync = ref.watch(imageCreditsProvider);

    return Scaffold(
      backgroundColor: theme.colorScheme.surface,
      appBar: AppBar(
        title: const Text('Photo credits'),
        backgroundColor: theme.colorScheme.surface,
        foregroundColor: theme.colorScheme.onSurface,
        elevation: 0,
      ),
      body: creditsAsync.when(
        loading: () => const Center(child: CircularProgressIndicator()),
        error: (e, _) => Center(
          child: Text('Could not load credits', style: theme.textTheme.body),
        ),
        data: (credits) {
          if (credits.isEmpty) {
            return Center(
              child: Text('No bundled photos yet.', style: theme.textTheme.body),
            );
          }

          final visible = _query.isEmpty
              ? credits
              : credits
                    .where(
                      (c) =>
                          c.imageKey.toLowerCase().contains(_query) ||
                          c.author.toLowerCase().contains(_query),
                    )
                    .toList();

          return ListView(
            padding: const EdgeInsets.fromLTRB(16, 8, 16, 32),
            children: [
              const _WhyCard(),
              const SizedBox(height: 14),
              _SearchField(
                onChanged: (v) => setState(() => _query = v.toLowerCase().trim()),
                count: credits.length,
              ),
              const SizedBox(height: 14),
              if (visible.isEmpty)
                Padding(
                  padding: const EdgeInsets.symmetric(vertical: 40),
                  child: Center(
                    child: Text(
                      'No photos match "$_query".',
                      style: theme.textTheme.caption,
                    ),
                  ),
                )
              else
                for (final credit in visible)
                  Padding(
                    padding: const EdgeInsets.only(bottom: 10),
                    child: _CreditTile(credit: credit),
                  ),
            ],
          );
        },
      ),
    );
  }
}

